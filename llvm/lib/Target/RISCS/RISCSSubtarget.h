#ifndef __LLVM_LIB_TARGET_RISCS_RISCSSUBTARGET_H__
#define __LLVM_LIB_TARGET_RISCS_RISCSSUBTARGET_H__

#include "MCTargetDesc/RISCSInfo.h"
#include "RISCSRegisterInfo.h"
#include "RISCSFrameLowering.h"
#include "RISCSISelLowering.h"
#include "RISCSInstrsInfo.h"
#include "llvm/CodeGen/SelectionDAGTargetInfo.h"
#include "llvm/CodeGen/TargetSubtargetInfo.h"
#include <string>

#define GET_SUBTARGETINFO_HEADER
#include "RISCSGenSubtargetInfo.inc"

namespace llvm {

class TargetMachine;

class RISCSSubtarget : public RISCSGenSubtargetInfo {
  virtual void anchor();

  RISCSRegisterInfo RegInfo;
  RISCSInstrInfo InstrInfo;
  RISCSFrameLowering FrameLowering;
  RISCSTargetLowering TLInfo;
  SelectionDAGTargetInfo TSInfo;
  riscsABI::ABI TargetABI = riscsABI::ABI_LP64;
  MVT XLenVT = MVT::i64;
  unsigned XLen = 64;

public:
  RISCSSubtarget(const Triple &TT, const std::string &CPU, const std::string &FS,
                  const TargetMachine &TM);

  /// Definition of function is auto generated by tblgen.
  void ParseSubtargetFeatures(StringRef CPU, StringRef TuneCPU, StringRef FS);

  const RISCSInstrInfo *getInstrInfo() const override { return &InstrInfo; }
  const RISCSFrameLowering *getFrameLowering() const override {
    return &FrameLowering;
  }
  const RISCSTargetLowering *getTargetLowering() const override {
    return &TLInfo;
  }
  const RISCSRegisterInfo *getRegisterInfo() const override { return &RegInfo; }
  const SelectionDAGTargetInfo *getSelectionDAGInfo() const override {
    return &TSInfo;
  }

  auto getTargetABI() const { return TargetABI; }
  auto getXLenVT() const { return XLenVT; }
  auto getXLen() const { return XLen; }
};

} // end namespace llvm

#endif // __LLVM_LIB_TARGET_RISCS_RISCSSUBTARGET_H__
